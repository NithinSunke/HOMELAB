"""Generation of the RMAN command file and the shell wrapper that runs it.

The wrapper is what actually executes on the target. It is launched detached
so a dropped SSH session never kills a running backup; it records the RMAN
exit code in a status file, which is how the runner detects completion.
"""
from __future__ import annotations

import datetime as dt
import shlex

from .models import Job, Target

# RMAN syntax for each backup level. A level 1 backup is differential unless
# CUMULATIVE is stated, so LEVEL1_DIFF is simply the bare form.
_LEVEL_CLAUSE = {
    "LEVEL0": "INCREMENTAL LEVEL 0",
    "LEVEL1_CUM": "INCREMENTAL LEVEL 1 CUMULATIVE",
    "LEVEL1_DIFF": "INCREMENTAL LEVEL 1",
}

HUMAN_NAMES = {
    "LEVEL0": "Level 0 (full baseline)",
    "LEVEL1_CUM": "Level 1 cumulative",
    "LEVEL1_DIFF": "Level 1 differential",
    "ARCHIVELOG": "Archive logs only",
}


def make_tag(target: Target, backup_type: str, when: dt.datetime | None = None) -> str:
    """Build an RMAN tag. Tags are limited to 30 characters and uppercased."""
    when = when or dt.datetime.now(dt.timezone.utc)
    short = {
        "LEVEL0": "L0",
        "LEVEL1_CUM": "L1C",
        "LEVEL1_DIFF": "L1D",
        "ARCHIVELOG": "ARC",
    }[backup_type]
    stamp = when.strftime("%Y%m%d_%H%M%S")
    return f"{short}_{stamp}"[:30].upper()


def build_script(target: Target, job: Job) -> str:
    """Return the full RMAN command file for this job."""
    lines: list[str] = []
    lines.append("CONNECT TARGET /;")
    if target.catalog_connect:
        lines.append(f"CONNECT CATALOG {target.catalog_connect};")
    lines.append("")
    lines.append("SHOW ALL;")
    lines.append("")
    lines.append("RUN {")

    # Channels. Without an explicit format RMAN writes to the Fast Recovery
    # Area, which is the right default for most configurations.
    for n in range(1, target.channels + 1):
        if target.backup_format:
            fmt = f"{target.backup_format.rstrip('/')}/%d_{job.tag}_%U"
            lines.append(
                f"  ALLOCATE CHANNEL c{n} DEVICE TYPE DISK FORMAT '{fmt}';"
            )
        else:
            lines.append(f"  ALLOCATE CHANNEL c{n} DEVICE TYPE DISK;")

    backupset = "AS COMPRESSED BACKUPSET" if target.compressed else "AS BACKUPSET"

    if job.backup_type == "ARCHIVELOG":
        delete = " DELETE INPUT" if job.delete_archivelog else ""
        lines.append(
            f"  BACKUP {backupset} ARCHIVELOG ALL TAG '{job.tag}'{delete};"
        )
    else:
        level = _LEVEL_CLAUSE[job.backup_type]
        lines.append(f"  BACKUP {backupset} {level} DATABASE TAG '{job.tag}';")
        if job.include_archivelog:
            delete = " DELETE INPUT" if job.delete_archivelog else ""
            lines.append(
                f"  BACKUP {backupset} ARCHIVELOG ALL "
                f"TAG '{job.tag}_ARC'{delete};"
            )

    if job.backup_controlfile:
        lines.append(f"  BACKUP CURRENT CONTROLFILE TAG '{job.tag}_CTL';")

    for n in range(1, target.channels + 1):
        lines.append(f"  RELEASE CHANNEL c{n};")

    lines.append("}")
    lines.append("")
    lines.append("LIST BACKUP SUMMARY;")
    lines.append("EXIT;")
    return "\n".join(lines) + "\n"


def build_wrapper(target: Target, remote_dir: str) -> str:
    """Shell script that sets the Oracle environment and runs RMAN.

    Everything the script prints goes into backup.log, because the launching
    shell may not be able to write into this directory once it is owned by
    the Oracle user. The script records its own pid so a cancel can signal
    the process group even when it runs under sudo as another user.

    Every interpolated value is quoted with shlex.quote. Values have already
    been pattern-checked on input, so this is belt and braces.
    """
    oracle_home = shlex.quote(target.oracle_home)
    oracle_sid = shlex.quote(target.oracle_sid)
    workdir = shlex.quote(remote_dir)

    return f"""#!/bin/bash
# Generated by rman-console. Safe to delete once the job has finished.
set -u
umask 022

cd {workdir} || exit 90
exec >> backup.log 2>&1
echo $$ > pid

export ORACLE_HOME={oracle_home}
export ORACLE_SID={oracle_sid}
export PATH="$ORACLE_HOME/bin:$PATH"
export LD_LIBRARY_PATH="$ORACLE_HOME/lib:${{LD_LIBRARY_PATH:-}}"
export NLS_DATE_FORMAT='YYYY-MM-DD HH24:MI:SS'

echo "=== rman-console starting at $(date -u +'%Y-%m-%d %H:%M:%S UTC') ==="
echo "running as $(id -un) on $(hostname)"
echo "ORACLE_HOME=$ORACLE_HOME"
echo "ORACLE_SID=$ORACLE_SID"
echo

"$ORACLE_HOME/bin/rman" cmdfile=backup.rman log=backup.log append
rc=$?

echo
echo "=== rman exited with $rc at $(date -u +'%Y-%m-%d %H:%M:%S UTC') ==="
echo "$rc" > status
exit "$rc"
"""


def summarise_errors(log_text: str, limit: int = 10) -> str | None:
    """Pull RMAN and Oracle error lines out of a log for the job summary."""
    hits = [
        line.strip()
        for line in log_text.splitlines()
        if line.lstrip().startswith(("RMAN-", "ORA-"))
    ]
    if not hits:
        return None
    # Preserve order, drop duplicates.
    seen: list[str] = []
    for h in hits:
        if h not in seen:
            seen.append(h)
    out = seen[:limit]
    if len(seen) > limit:
        out.append(f"... and {len(seen) - limit} more")
    return "\n".join(out)
